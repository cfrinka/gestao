import * as React from "react";
import { cn } from "@/lib/utils";

// A sheet of card stock: white, hairline edge, square, no lift.
const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-sm border border-rule bg-paper text-ink",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

